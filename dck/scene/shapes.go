// GetCopy returns a copy of the shape
func (sm *ShapeManager) GetCopy(name string) *Shape {
	original, ok := sm.shapes[name]
	if !ok {
		return &Shape{Points: []Vector3{}}
	}

	// Deep copy
	points := make([]Vector3, len(original.Points))
	copy(points, original.Points)
	return &Shape{Points: points}
}

// XYZ/SetXYZ let DCK animate coordinates while keeping the authored ball index.
func (s *Shape) Len() int { return len(s.Points) }
func (s *Shape) XYZ(index int) geometry.Vec3 {
	p := s.Points[index]
	return geometry.Vec3{X: p.X, Y: p.Y, Z: p.Z}
}
func (s *Shape) SetXYZ(index int, p geometry.Vec3) {
	point := &s.Points[index]
	point.X, point.Y, point.Z = p.X, p.Y, p.Z
}

func (sm *ShapeManager) Clone(name string) (geometry.PointWriter, error) {
	if _, ok := sm.shapes[name]; !ok {
		return nil, fmt.Errorf("vectorballs: unknown shape %q", name)
	}
	return sm.GetCopy(name), nil
}

func (sm *ShapeManager) Target(name string) (geometry.PointReader, error) {
	shape, ok := sm.shapes[name]
	if !ok {
		return nil, fmt.Errorf("vectorballs: unknown target %q", name)
	}
	return shape, nil
}
